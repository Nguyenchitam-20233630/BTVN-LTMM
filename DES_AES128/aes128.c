uint8_t nhan_gf2_8(int a, int b)
{
    int ket_qua = 0;

    for (int i = 0; i < 8; i++) {
        if (b & 1) {
            ket_qua ^= a;
        }

        b >>= 1;
        a <<= 1;

        if (a >= 256) {
            a ^= 0x11B;
        }
    }

    return (uint8_t)ket_qua;
}
